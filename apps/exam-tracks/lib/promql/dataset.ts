/**
 * The playground's built-in data: three hours of scrapes from a small, made-up
 * fleet, generated deterministically so the browser and the golden-test export
 * (scripts/playground-export.ts) produce identical samples.
 *
 * Story the data tells (times relative to the end of the data):
 *  - api-2 has an incident from -50m to -35m: 5xx errors and latency spike.
 *  - api-3 restarts at -80m (down for two scrapes; counters reset; version 1.4.2 → 1.5.0).
 *  - api-1 slowly leaks memory.
 *  - node-2's root filesystem is filling up steadily.
 *  - The nightly-report batch job last succeeded 26 hours ago; cleanup ran 40 minutes ago.
 */

export type Labels = Record<string, string>;
export type StoredSeries = { labels: Labels; t: Float64Array; v: Float64Array };
export type MetricType = "counter" | "gauge" | "histogram" | "summary";
export type FamilyMeta = { type: MetricType; help: string };
export type Dataset = { series: StoredSeries[]; families: Record<string, FamilyMeta>; start: number; end: number; scrapeMs: number };

export const DATA_END = Date.UTC(2026, 9, 1, 12, 0, 0); // 1 Oct 2026 12:00 UTC
export const DATA_HOURS = 3;
export const SCRAPE_MS = 15_000;
export const DATA_START = DATA_END - DATA_HOURS * 3_600_000;

const MIN = 60_000;

function hash(s: string): number {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 16777619);
  return h >>> 0;
}
function rng(seed: string) {
  let a = hash(seed);
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
/** Round to a fixed number of decimals so values stay readable and round-trip exactly as text. */
const r = (x: number, d = 3) => Math.round(x * 10 ** d) / 10 ** d;

type Target = { job: string; instance: string; phaseMs: number; downFrom?: number; downTo?: number };

const TARGETS: Target[] = [
  { job: "api", instance: "api-1:8080", phaseMs: 1_000 },
  { job: "api", instance: "api-2:8080", phaseMs: 6_000 },
  { job: "api", instance: "api-3:8080", phaseMs: 11_000, downFrom: -80 * MIN - 30_000, downTo: -80 * MIN },
  { job: "db", instance: "db-1:9187", phaseMs: 3_000 },
  { job: "node", instance: "node-1:9100", phaseMs: 2_000 },
  { job: "node", instance: "node-2:9100", phaseMs: 9_000 },
  { job: "worker", instance: "worker-1:8000", phaseMs: 4_000 },
  { job: "pushgateway", instance: "pushgateway:9091", phaseMs: 7_000 },
];

const API3_RESTART = DATA_END - 80 * MIN;
const INCIDENT_FROM = DATA_END - 50 * MIN, INCIDENT_TO = DATA_END - 35 * MIN;
const BUCKETS = [0.05, 0.1, 0.25, 0.5, 1, 2.5];

export const FAMILIES: Record<string, FamilyMeta> = {
  up: { type: "gauge", help: "1 if the last scrape of the target succeeded, 0 if it failed (generated by Prometheus)." },
  scrape_duration_seconds: { type: "gauge", help: "How long the last scrape took (generated by Prometheus)." },
  http_requests_total: { type: "counter", help: "Total HTTP requests handled, by method, path and status." },
  http_request_duration_seconds: { type: "histogram", help: "HTTP request latency in seconds (classic histogram)." },
  process_start_time_seconds: { type: "gauge", help: "Start time of the process since the Unix epoch, in seconds." },
  process_cpu_seconds_total: { type: "counter", help: "Total user and system CPU time spent, in seconds." },
  process_resident_memory_bytes: { type: "gauge", help: "Resident memory size in bytes." },
  app_build_info: { type: "gauge", help: "Build information. Always 1; the data is in the labels." },
  db_connections: { type: "gauge", help: "Open database connections by state." },
  db_queries_total: { type: "counter", help: "Total database queries by type." },
  db_query_duration_seconds: { type: "summary", help: "Database query latency in seconds (summary with client-side quantiles)." },
  node_cpu_seconds_total: { type: "counter", help: "Seconds each CPU spent in each mode." },
  node_memory_MemAvailable_bytes: { type: "gauge", help: "Memory available for new work, in bytes." },
  node_memory_MemTotal_bytes: { type: "gauge", help: "Total memory, in bytes." },
  node_filesystem_avail_bytes: { type: "gauge", help: "Filesystem space available to non-root users, in bytes." },
  node_filesystem_size_bytes: { type: "gauge", help: "Filesystem size, in bytes." },
  node_load1: { type: "gauge", help: "1-minute load average." },
  node_boot_time_seconds: { type: "gauge", help: "Node boot time since the Unix epoch, in seconds." },
  node_network_receive_bytes_total: { type: "counter", help: "Network bytes received, by device." },
  queue_depth: { type: "gauge", help: "Jobs waiting in each queue." },
  worker_jobs_processed_total: { type: "counter", help: "Jobs processed, by queue and result." },
  batch_job_last_success_timestamp_seconds: { type: "gauge", help: "Unix time of the batch job's last successful run (pushed via the Pushgateway)." },
  batch_job_duration_seconds: { type: "gauge", help: "How long the batch job's last run took, in seconds (pushed)." },
};

/** Familiy name for a series name (strips histogram/summary suffixes). */
export function familyOf(name: string): string {
  if (FAMILIES[name]) return name;
  for (const suf of ["_bucket", "_sum", "_count"]) if (name.endsWith(suf) && FAMILIES[name.slice(0, -suf.length)]) return name.slice(0, -suf.length);
  return name;
}

/** Each series is always built with the same label insertion order, so no sort is needed. */
function labelKey(labels: Labels): string {
  let k = "";
  for (const n in labels) k += n + "\u0000" + labels[n] + "\u0001";
  return k;
}

class Builder {
  map = new Map<string, { labels: Labels; t: number[]; v: number[] }>();
  add(labels: Labels, t: number, v: number) {
    const key = labelKey(labels);
    let s = this.map.get(key);
    if (!s) this.map.set(key, (s = { labels, t: [], v: [] }));
    s.t.push(t);
    s.v.push(v);
  }
}

/** Smooth daily-ish wave plus noise, never negative. */
function wave(t: number, period: number, amp: number) {
  return 1 + amp * Math.sin((2 * Math.PI * (t - DATA_START)) / period);
}

export function generate(): Dataset {
  const b = new Builder();
  const state = new Map<string, number>();
  const counter = (labels: Labels, t: number, inc: number, reset = false) => {
    const key = labelKey(labels);
    const prev = reset ? 0 : state.get(key) ?? 0;
    const next = r(prev + Math.max(0, inc));
    state.set(key, next);
    b.add(labels, t, next);
  };

  for (const tg of TARGETS) {
    const rand = rng(tg.instance);
    const base = { job: tg.job, instance: tg.instance };
    let resetPending = false;
    for (let t = DATA_START + tg.phaseMs; t <= DATA_END; t += SCRAPE_MS) {
      const rel = t - DATA_END;
      const down = tg.downFrom !== undefined && rel >= tg.downFrom && rel < tg.downTo!;
      b.add({ __name__: "up", ...base }, t, down ? 0 : 1);
      b.add({ __name__: "scrape_duration_seconds", ...base }, t, r(down ? 10 : 0.004 + rand() * 0.02, 4));
      if (down) { resetPending = true; continue; }
      const reset = resetPending;
      resetPending = false;
      const inIncident = tg.instance === "api-2:8080" && t >= INCIDENT_FROM && t < INCIDENT_TO;

      if (tg.job === "api") {
        const restarted = tg.instance === "api-3:8080" && t >= API3_RESTART;
        const startTime = tg.instance === "api-3:8080" ? (restarted ? API3_RESTART / 1000 - 12 : DATA_START / 1000 - 86_400 * 2) : DATA_START / 1000 - 86_400 * (tg.instance === "api-1:8080" ? 6 : 4);
        b.add({ __name__: "process_start_time_seconds", ...base }, t, startTime);
        b.add({ __name__: "app_build_info", ...base, version: restarted ? "1.5.0" : "1.4.2", goversion: "go1.25.1" }, t, 1);
        const load = wave(t, 3 * 3_600_000, 0.25);
        const routes: [string, string, number][] = [["GET", "/api/orders", 6], ["POST", "/api/orders", 1.5], ["GET", "/api/users", 3], ["GET", "/healthz", 0.2]];
        for (const [method, path, rps] of routes) {
          const ok = rps * load * (0.9 + rand() * 0.2) * 15;
          const errRate = inIncident ? 0.18 : path === "/healthz" ? 0 : 0.004;
          const statuses: [string, number][] = [["200", ok * (1 - errRate)], ["500", ok * errRate]];
          if (path === "/api/users") statuses.push(["404", ok * 0.02]);
          for (const [status, n] of statuses) {
            if (path === "/healthz" && status !== "200") continue;
            counter({ __name__: "http_requests_total", ...base, method, path, status }, t, Math.round(n + rand() * 0.6), reset);
          }
        }
        // Latency histogram per path.
        for (const [path, rps, median] of [["/api/orders", 7.5, 0.08], ["/api/users", 3, 0.12], ["/healthz", 0.2, 0.004]] as [string, number, number][]) {
          const n = Math.round(rps * load * 15 * (0.9 + rand() * 0.2));
          const med = inIncident ? median * 6 : median;
          const hl = { ...base, path };
          // Log-uniform latency around the median, plus a 3% slow tail; bucket shares computed analytically.
          const share = (le: number, shift: number) => Math.min(1, Math.max(0, (Math.log(le / med) - shift + 1.1) / 2.2));
          const counts = [...BUCKETS.map((le) => Math.round(n * (0.97 * share(le, 0) + 0.03 * share(le, 1.6)))), n];
          const sumInc = n * med * 1.2 * (0.97 + 0.03 * Math.exp(1.6)) * (0.95 + rand() * 0.1);
          BUCKETS.forEach((le, k) => counter({ __name__: "http_request_duration_seconds_bucket", ...hl, le: String(le) }, t, counts[k], reset));
          counter({ __name__: "http_request_duration_seconds_bucket", ...hl, le: "+Inf" }, t, counts[BUCKETS.length], reset);
          counter({ __name__: "http_request_duration_seconds_count", ...hl }, t, counts[BUCKETS.length], reset);
          counter({ __name__: "http_request_duration_seconds_sum", ...hl }, t, r(sumInc, 4), reset);
        }
        counter({ __name__: "process_cpu_seconds_total", ...base }, t, r(0.6 * load + rand() * 0.3 + (inIncident ? 1.2 : 0)), reset);
        const leak = tg.instance === "api-1:8080" ? ((t - DATA_START) / 3_600_000) * 42e6 : 0;
        b.add({ __name__: "process_resident_memory_bytes", ...base }, t, Math.round(180e6 + leak + rand() * 6e6));
      }

      if (tg.job === "db") {
        b.add({ __name__: "db_connections", ...base, state: "active" }, t, Math.round(12 * wave(t, 3 * 3_600_000, 0.3) + rand() * 4));
        b.add({ __name__: "db_connections", ...base, state: "idle" }, t, Math.round(20 + rand() * 5));
        const sel = Math.round(40 * wave(t, 3 * 3_600_000, 0.25) * 15 * (0.9 + rand() * 0.2));
        const ins = Math.round(8 * 15 * (0.9 + rand() * 0.2));
        counter({ __name__: "db_queries_total", ...base, type: "select" }, t, sel);
        counter({ __name__: "db_queries_total", ...base, type: "insert" }, t, ins);
        for (const [q, v] of [["0.5", 0.003], ["0.9", 0.011], ["0.99", 0.045]] as [string, number][])
          b.add({ __name__: "db_query_duration_seconds", ...base, quantile: q }, t, r(v * (0.85 + rand() * 0.3), 5));
        counter({ __name__: "db_query_duration_seconds_count", ...base }, t, sel + ins);
        counter({ __name__: "db_query_duration_seconds_sum", ...base }, t, r((sel + ins) * 0.0052, 4));
      }

      if (tg.job === "node") {
        const n2 = tg.instance === "node-2:9100";
        for (const cpu of ["0", "1"]) {
          const busy = (n2 ? 0.55 : 0.25) * wave(t, 3 * 3_600_000, 0.2);
          const user = 15 * busy * 0.7 * (0.9 + rand() * 0.2), system = 15 * busy * 0.25 * (0.9 + rand() * 0.2), iowait = 15 * busy * 0.05 * rand();
          counter({ __name__: "node_cpu_seconds_total", ...base, cpu, mode: "user" }, t, r(user, 2));
          counter({ __name__: "node_cpu_seconds_total", ...base, cpu, mode: "system" }, t, r(system, 2));
          counter({ __name__: "node_cpu_seconds_total", ...base, cpu, mode: "iowait" }, t, r(iowait, 2));
          counter({ __name__: "node_cpu_seconds_total", ...base, cpu, mode: "idle" }, t, r(Math.max(0, 15 - user - system - iowait), 2));
        }
        const total = n2 ? 8 * 2 ** 30 : 16 * 2 ** 30;
        b.add({ __name__: "node_memory_MemTotal_bytes", ...base }, t, total);
        b.add({ __name__: "node_memory_MemAvailable_bytes", ...base }, t, Math.round(total * (n2 ? 0.22 : 0.61) + rand() * 2e8));
        const size = 100 * 2 ** 30;
        const fsl = { ...base, device: "/dev/sda1", mountpoint: "/", fstype: "ext4" };
        b.add({ __name__: "node_filesystem_size_bytes", ...fsl }, t, size);
        const avail = n2 ? 30 * 2 ** 30 - ((t - DATA_START) / 3_600_000) * 6 * 2 ** 30 : 61 * 2 ** 30;
        b.add({ __name__: "node_filesystem_avail_bytes", ...fsl }, t, Math.round(avail + rand() * 5e6));
        b.add({ __name__: "node_load1", ...base }, t, r((n2 ? 1.6 : 0.5) * wave(t, 3 * 3_600_000, 0.2) + rand() * 0.3, 2));
        b.add({ __name__: "node_boot_time_seconds", ...base }, t, DATA_START / 1000 - 86_400 * (n2 ? 12 : 40));
        counter({ __name__: "node_network_receive_bytes_total", ...base, device: "eth0" }, t, Math.round(15 * 1.2e6 * wave(t, 3 * 3_600_000, 0.3) * (0.8 + rand() * 0.4)));
      }

      if (tg.job === "worker") {
        // Email queue: hovers around 30, backs up during a spike from -25m to -10m, then drains.
        const spike = t >= DATA_END - 25 * MIN && t < DATA_END - 10 * MIN;
        const prev = state.get("q:email") ?? 30;
        const drift = spike ? 6 : prev > 32 ? -8 : (30 - prev) * 0.2;
        const email = Math.max(0, Math.round(prev + drift + (rand() - 0.5) * 6));
        state.set("q:email", email);
        b.add({ __name__: "queue_depth", ...base, queue: "email" }, t, email);
        b.add({ __name__: "queue_depth", ...base, queue: "sms" }, t, Math.round(3 + rand() * 4));
        for (const queue of ["email", "sms"]) {
          counter({ __name__: "worker_jobs_processed_total", ...base, queue, result: "success" }, t, Math.round((queue === "email" ? 20 : 5) * (0.9 + rand() * 0.2)));
          counter({ __name__: "worker_jobs_processed_total", ...base, queue, result: "failure" }, t, rand() < 0.05 ? 1 : 0);
        }
      }

      if (tg.job === "pushgateway") {
        // Pushed batch metrics keep their exported job label (honor_labels: true).
        const cleanupRanAt = Math.floor((t - 20 * MIN) / (60 * MIN)) * 60 * MIN + 20 * MIN; // hourly, at 20 past
        const pushed = [
          { task: "nightly-report", last: DATA_END - 26 * 3_600_000, dur: 1260 },
          { task: "cleanup", last: cleanupRanAt, dur: 42 },
        ];
        for (const p of pushed) {
          const pl = { job: "batch", task: p.task };
          b.add({ __name__: "batch_job_last_success_timestamp_seconds", ...pl }, t, Math.round(p.last / 1000));
          b.add({ __name__: "batch_job_duration_seconds", ...pl }, t, p.dur);
        }
      }
    }
  }

  const series = [...b.map.values()].map((s) => ({ labels: s.labels, t: Float64Array.from(s.t), v: Float64Array.from(s.v) }));
  return { series, families: FAMILIES, start: DATA_START, end: DATA_END, scrapeMs: SCRAPE_MS };
}
